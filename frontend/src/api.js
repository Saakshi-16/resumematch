// Small helpers so every page talks to Django the same way.

export async function getJSON(url) {
  const res = await fetch(url);
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error || `Request failed (${res.status})`);
  return data;
}

export async function postJSON(url, body) {
  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body || {}),
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error || `Request failed (${res.status})`);
  return data;
}

export async function postForm(url, formData) {
  const res = await fetch(url, { method: "POST", body: formData });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error || `Request failed (${res.status})`);
  return data;
}

// Remember the current analysis in this browser tab
export const getAnalysisId = () => sessionStorage.getItem("analysisId");
export const setAnalysisId = (id) => {
  sessionStorage.setItem("analysisId", id);
  sessionStorage.removeItem("chat");
};
export const getUser = () => JSON.parse(localStorage.getItem("user") || "null");
